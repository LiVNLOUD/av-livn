// Embeds apps/web/dist into a TS module served by the Worker.
// Why: the session proxy rewrites Authorization headers, which breaks wrangler's
// JWT-based static-asset upload. Embedding keeps deploy to one script upload.
import { readdirSync, readFileSync, statSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, relative, extname } from 'node:path';
import { createHash } from 'node:crypto';

const root = new URL('..', import.meta.url).pathname;
const dist = join(root, 'apps/web/dist');
const out = join(root, 'workers/api/src/generated/assets.ts');

const TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.mjs': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.webmanifest': 'application/manifest+json',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.ico': 'image/x-icon',
  '.txt': 'text/plain; charset=utf-8',
  '.xml': 'application/xml',
  '.woff2': 'font/woff2',
};
const TEXT = new Set(['.html', '.js', '.mjs', '.css', '.json', '.webmanifest', '.svg', '.txt', '.xml']);

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

const entries = walk(dist).map((file) => {
  const ext = extname(file);
  const buf = readFileSync(file);
  const path = '/' + relative(dist, file).split('\\').join('/');
  return {
    path,
    type: TYPES[ext] ?? 'application/octet-stream',
    etag: createHash('sha1').update(buf).digest('hex').slice(0, 16),
    encoding: TEXT.has(ext) ? 'utf8' : 'base64',
    body: TEXT.has(ext) ? buf.toString('utf8') : buf.toString('base64'),
  };
});

mkdirSync(join(root, 'workers/api/src/generated'), { recursive: true });
writeFileSync(
  out,
  '// GENERATED by scripts/embed-assets.mjs. Do not edit.\n' +
    "import type { EmbeddedAsset } from '../assets';\n" +
    `export const ASSETS: Record<string, EmbeddedAsset> = ${JSON.stringify(Object.fromEntries(entries.map((e) => [e.path, e])))};\n`,
);
console.log(`embedded ${entries.length} files from apps/web/dist`);
